func (fe *frontendServer) convertCurrency(ctx context.Context, money *model.Money, currency string) (*model.Money, error) {
	if avoidNoopCurrencyConversionRPC && money.CurrencyCode == currency {
		return money, nil
	}
	return fe.currencySvc.Convert(ctx, money, currency)
}

func (fe *frontendServer) getShippingQuote(ctx context.Context, items []*model.CartItem, currency string) (*model.Money, error) {
	quote, err := fe.shippingSvc.GetQuote(ctx, items, currency)
	if err != nil {
		return nil, err
	}
	// shipping service might return USD, we might need to convert?
	// The new interface `GetQuote` has `currency` param, so assuming it returns in that currency.
	// But `handlers.go` uses `fe.convertCurrency(ctx, quote.GetCostUsd(), currency)`.
	// If my shipping service REST API returns CostUsd (as implied by my clients.go: CostUsd *model.Money),
	// then I need to convert.

	// My `clients.go` `GetQuote` returns `out.CostUsd`.
	// So I should convert it.

	localized, err := fe.convertCurrency(ctx, quote, currency)
	return localized, errors.Wrap(err, "failed to convert currency for shipping cost")
}

